// Scans public/audio for recorded files, rewrites src/content/audio-manifest.json,
// and writes docs/RECORDING_LIST.md (what is recorded, what is still needed).
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const decoded = decodeURIComponent(root);
const phonemes = JSON.parse(readFileSync(join(decoded, 'src/content/phonemes.json'), 'utf8'));
const letters = 'abcdefghijklmnopqrstuvwxyz'.split('');

const list = (dir) => {
  const p = join(decoded, 'public/audio', dir);
  return existsSync(p)
    ? readdirSync(p)
        .filter((f) => f.endsWith('.mp3'))
        .map((f) => f.replace(/\.mp3$/, ''))
    : [];
};

const manifest = { phonemes: list('phonemes'), letters: list('letters'), words: list('words') };
writeFileSync(join(decoded, 'src/content/audio-manifest.json'), JSON.stringify(manifest) + '\n');

const mark = (have, id) => (have.includes(id) ? '[x]' : '[ ]');
let md = `# Recording list

Generated by \`npm run audio:list\`. Record each item as a short mono MP3 (~0.5-1.5 s, trim silence),
save to the path shown, then re-run \`npm run audio:list\`. Anything not recorded falls back to text-to-speech.

## Sounds -> \`public/audio/phonemes/<id>.mp3\` (${manifest.phonemes.length}/${phonemes.length} done)

Say the PURE sound only (e.g. /s/ = "sss", never "suh"). Stop consonants (t, p, k, d, b, g) are quick and unvoiced/voiced with no vowel added.

| Done | File | Letters | Example word | Note |
|---|---|---|---|---|
`;
for (const p of phonemes) {
  md += `| ${mark(manifest.phonemes, p.id)} | \`${p.id}.mp3\` | ${p.grapheme} | ${p.example} | ${p.note} |\n`;
}
md += `\n## Letter names -> \`public/audio/letters/<a-z>.mp3\` (${manifest.letters.length}/26 done)\n\nSay the letter NAME ("ay", "bee", "see"...).\n\n`;
md += letters.map((l) => `- ${mark(manifest.letters, l)} \`${l}.mp3\``).join('\n') + '\n';
md += `\n## Words and sentences -> \`public/audio/words/<wordId>.mp3\`\n\nOptional upgrade for later phases (word IDs come from the content files). Currently recorded: ${manifest.words.length}.\n`;

mkdirSync(join(decoded, 'docs'), { recursive: true });
writeFileSync(join(decoded, 'docs/RECORDING_LIST.md'), md);
console.log(
  `phonemes ${manifest.phonemes.length}/${phonemes.length}, letters ${manifest.letters.length}/26, words ${manifest.words.length}`,
);
